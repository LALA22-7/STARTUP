# 6.4.3 — POST /prescription/send returns HTTP 200 on success, 502 on failure
# ---------------------------------------------------------------------------

PRESCRIPTION_PAYLOAD = {
    "to_phone": "919999999999",
    "patient_name": "Ravi Kumar",
    "doctor_name": "Dr. Sharma",
    "medications": [
        {"name": "Paracetamol", "dose": "500mg", "frequency": "Twice daily", "duration": "5 days"}
    ],
    "instructions": "Take after meals.",
}

ENV_PATCH = {
    "DATABASE_URL": "sqlite+aiosqlite:///:memory:",
    "META_PHONE_ID": "test_phone_id",
    "META_ACCESS_TOKEN": "test_access_token",
}


def test_prescription_endpoint_returns_200_on_success():
    """
    POST /prescription/send must return HTTP 200 when PDF delivery succeeds.
    Validates: Requirements 8.4
    """
    with patch.dict(os.environ, ENV_PATCH):
        with patch("app.main.start_scheduler"):
            with patch("app.main.stop_scheduler"):
                with patch("app.main.send_prescription_pdf", new=AsyncMock(return_value=True)):
                    from app.main import app as fastapi_app

                    with TestClient(fastapi_app) as client:
                        response = client.post("/prescription/send", json=PRESCRIPTION_PAYLOAD)

    assert response.status_code == 200, (
        f"Expected HTTP 200, got {response.status_code}: {response.text}"
    )
    body = response.json()
    assert body.get("status") == "success"


def test_prescription_endpoint_returns_502_on_failure():
    """
    POST /prescription/send must return HTTP 502 when PDF delivery fails.
    Validates: Requirements 8.5
    """
    with patch.dict(os.environ, ENV_PATCH):
        with patch("app.main.start_scheduler"):
            with patch("app.main.stop_scheduler"):
                with patch("app.main.send_prescription_pdf", new=AsyncMock(return_value=False)):
                    from app.main import app as fastapi_app

                    with TestClient(fastapi_app) as client:
                        response = client.post("/prescription/send", json=PRESCRIPTION_PAYLOAD)

    assert response.status_code == 502, (
        f"Expected HTTP 502, got {response.status_code}: {response.text}"
    )
    body = response.json()
    assert "detail" in body
