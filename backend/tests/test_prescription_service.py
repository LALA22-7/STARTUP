# 6.4.2 — send_prescription_pdf() uploads to Meta API and sends document
# ---------------------------------------------------------------------------

def test_send_prescription_pdf_calls_upload_and_send():
    """
    send_prescription_pdf() must call upload_whatsapp_media() and then
    send_whatsapp_document() on success.
    Validates: Requirements 8.2, 8.3
    """
    from app.main import send_prescription_pdf

    mock_media_id = "media_abc123"

    async def _run():
        with patch("app.main.upload_whatsapp_media", new=AsyncMock(return_value=mock_media_id)) as mock_upload:
            with patch("app.main.send_whatsapp_document", new=AsyncMock()) as mock_send_doc:
                with patch("app.main.send_whatsapp_text", new=AsyncMock()):
                    result = await send_prescription_pdf(
                        to_phone="919999999999",
                        patient_name="Ravi Kumar",
                        doctor_name="Dr. Sharma",
                        medications=[{"name": "Paracetamol", "dose": "500mg", "frequency": "Twice daily", "duration": "5 days"}],
                        instructions="Take after meals.",
                    )

        assert result is True, "send_prescription_pdf must return True on success"
        mock_upload.assert_called_once()
        mock_send_doc.assert_called_once()

        # Verify the document was sent to the correct phone
        call_kwargs = mock_send_doc.call_args
        assert call_kwargs.kwargs.get("to_phone") == "919999999999" or call_kwargs.args[0] == "919999999999"
        assert call_kwargs.kwargs.get("media_id") == mock_media_id or mock_media_id in call_kwargs.args

    run_async(_run())


def test_send_prescription_pdf_falls_back_to_text_on_upload_failure():
    """
    send_prescription_pdf() must send a fallback WhatsApp text message
    when the Meta API media upload fails.
    Validates: Requirements 8.5
    """
    from app.main import send_prescription_pdf

    fallback_messages = []

    async def mock_send_text(to_phone: str, text: str, **kwargs):
        fallback_messages.append({"to": to_phone, "text": text})

    async def _run():
        with patch("app.main.upload_whatsapp_media", new=AsyncMock(side_effect=RuntimeError("Upload failed"))):
            with patch("app.main.send_whatsapp_text", side_effect=mock_send_text):
                result = await send_prescription_pdf(
                    to_phone="919999999999",
                    patient_name="Ravi Kumar",
                    doctor_name="Dr. Sharma",
                    medications=[],
                    instructions="",
                )

        assert result is False, "send_prescription_pdf must return False on failure"
        assert len(fallback_messages) >= 1, "A fallback text message must be sent on failure"
        assert "919999999999" == fallback_messages[0]["to"]

    run_async(_run())


