# ---------------------------------------------------------------------------
# Async helper
# ---------------------------------------------------------------------------

def run_async(coro):
    loop = asyncio.new_event_loop()
    try:
        return loop.run_until_complete(coro)
    finally:
        loop.close()


# ---------------------------------------------------------------------------
# PDF text extraction helper
# ReportLab uses ASCII85Decode + FlateDecode (two-filter chain) on content
# streams. We patch reportlab's global compress flag to disable compression
# so the content stream is readable for text assertions.
# ---------------------------------------------------------------------------

def generate_uncompressed_pdf(**kwargs) -> bytes:
    """
    Generate a prescription PDF with compression disabled.

    Patches reportlab.rl_config.pageCompression and useA85 so the content
    stream is written as plain uncompressed text, making it searchable in
    the raw bytes for assertion purposes.
    """
    import reportlab.rl_config as _rl_config
    orig_page_compression = _rl_config.pageCompression
    orig_use_a85 = _rl_config.useA85
    _rl_config.pageCompression = 0
    _rl_config.useA85 = 0
    try:
        from app.pdf_service import generate_prescription_pdf
        return generate_prescription_pdf(**kwargs)
    finally:
        _rl_config.pageCompression = orig_page_compression
        _rl_config.useA85 = orig_use_a85


